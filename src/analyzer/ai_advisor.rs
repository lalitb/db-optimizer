use crate::models::{QueryStats, TableInfo, IndexInfo, Recommendation, Severity, IssueType};
use anyhow::{Result, Context};
use async_trait::async_trait;
use serde::{Deserialize, Serialize};
use reqwest::Client;
use serde_json::json;

/// Interface for LLM interaction
#[async_trait]
pub trait LlmClient {
    async fn complete(&self, prompt: &str) -> Result<String>;
}

/// OpenAI implementation of LlmClient
pub struct OpenAiClient {
    client: Client,
    api_key: String,
    model: String,
}

impl OpenAiClient {
    pub fn new(api_key: String, model: String) -> Self {
        Self {
            client: Client::new(),
            api_key,
            model,
        }
    }
}

#[async_trait]
impl LlmClient for OpenAiClient {
    async fn complete(&self, prompt: &str) -> Result<String> {
        let response = self.client
            .post("https://api.openai.com/v1/chat/completions")
            .header("Authorization", format!("Bearer {}", self.api_key))
            .json(&json!({
                "model": self.model,
                "messages": [
                    {"role": "system", "content": "You are a PostgreSQL performance expert. Provide recommendations in valid JSON format only."},
                    {"role": "user", "content": prompt}
                ],
                "temperature": 0.0
            }))
            .send()
            .await
            .context("Failed to send request to OpenAI")?
            .json::<serde_json::Value>()
            .await
            .context("Failed to parse OpenAI response")?;

        let content = response["choices"][0]["message"]["content"]
            .as_str()
            .ok_or_else(|| anyhow::anyhow!("Invalid response structure from OpenAI"))?;
            
        Ok(content.to_string())
    }
}

/// AI-powered query advisor
pub struct AiAdvisor<T: LlmClient> {
    llm_client: T,
}

impl<T: LlmClient> AiAdvisor<T> {
    pub fn new(llm_client: T) -> Self {
        Self { llm_client }
    }

    /// Analyze a query using LLM
    pub async fn analyze_query(
        &self,
        query: &QueryStats,
        tables: &[TableInfo],
        indexes: &[IndexInfo],
    ) -> Result<Option<Recommendation>> {
        let prompt = self.build_prompt(query, tables, indexes);
        
        let response_text = self.llm_client.complete(&prompt).await?;
        
        // Extract JSON from response (handle markdown code blocks if present)
        let json_str = if let Some(start) = response_text.find("```json") {
            if let Some(end) = response_text[start..].find("```") {
                &response_text[start+7..start+end]
            } else {
                &response_text
            }
        } else if let Some(start) = response_text.find("{") {
            if let Some(end) = response_text.rfind("}") {
                &response_text[start..=end]
            } else {
                &response_text
            }
        } else {
            &response_text
        };

        let ai_rec: AiRecommendationResponse = serde_json::from_str(json_str)
            .context(format!("Failed to parse AI response as JSON: {}", json_str))?;

        // Convert to internal Recommendation model
        Ok(Some(Recommendation {
            id: format!("ai_optimization_{}", query.queryid.unwrap_or(0)),
            title: ai_rec.title,
            description: ai_rec.description,
            issue_type: IssueType::SlowQuery, // Defaulting to SlowQuery, could be inferred
            severity: match ai_rec.severity.to_uppercase().as_str() {
                "CRITICAL" => Severity::Critical,
                "HIGH" => Severity::High,
                "MEDIUM" => Severity::Medium,
                _ => Severity::Low,
            },
            affected_queries_count: Some(query.calls),
            estimated_time_savings_ms: None, // AI could estimate this too
            estimated_cost_savings_usd_monthly: None,
            migration_sql: ai_rec.migration_sql,
            rollback_sql: None,
            safety_notes: "Generated by AI. Review carefully before applying.".to_string(),
            affected_table: None, // Could be extracted
            affected_query: Some(query.query.clone()),
        }))
    }

    fn build_prompt(&self, query: &QueryStats, tables: &[TableInfo], indexes: &[IndexInfo]) -> String {
        let mut prompt = String::new();
        prompt.push_str("Analyze the following PostgreSQL query for performance issues:\n\n");
        prompt.push_str(&format!("Query: {}\n", query.query));
        prompt.push_str(&format!("Execution Time (mean): {:.2}ms\n", query.mean_exec_time_ms));
        prompt.push_str(&format!("Calls: {}\n", query.calls));
        
        prompt.push_str("\nRelevant Tables:\n");
        for table in tables {
            prompt.push_str(&format!("- {} ({} rows, {:.2} MB)\n", table.table_name, table.row_count, table.table_size_mb));
        }

        prompt.push_str("\nExisting Indexes:\n");
        for index in indexes {
            prompt.push_str(&format!("- {} on {}\n", index.index_name, index.table_name));
        }

        prompt.push_str("\nProvide recommendations in JSON format with the following fields:\n");
        prompt.push_str("- title\n- description\n- severity (LOW, MEDIUM, HIGH, CRITICAL)\n- migration_sql\n");
        
        prompt
    }
}

#[derive(Debug, Deserialize)]
struct AiRecommendationResponse {
    title: String,
    description: String,
    severity: String,
    migration_sql: String,
}
